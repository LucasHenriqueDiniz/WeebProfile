/**
 * Height of every WakaTime section against what the browsers draw.
 *
 * `MEASURED` is what Chrome 158, Firefox 150 and WebKit 26.4 (Playwright 1.60) drew on
 * 19/11/2026, measured by `pnpm --filter @weeb/svg-generator audit:heights -- --plugin=wakatime
 * --variants --engine=all --data-variants=<VARIANTS as a module>`: each section alone and all of
 * them in one card, with every option that changes the height, and the mock changed as
 * `VARIANTS` says. The period options only rescale the mock, so of those only `all_time` (the
 * longest range text beside the title) is kept here.
 *
 * Two defects the first measurement found: the terminal bar, left to the font, drew 19px in
 * Chrome and Firefox and 18 in WebKit (now a fixed 20px line), and a "(cached)" marker after the
 * range wrapped the Operating Systems title in half, 15px cut (removed).
 */

