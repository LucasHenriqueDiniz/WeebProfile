const plugin = PluginManager.getInstance().get("lastfm")!
let mock: LastFmData

beforeAll(async () => {
  const sections = ["statistics", "recent_tracks", "top_artists", "top_albums", "top_tracks"]
  mock = (await plugin.fetchData({ ...plugin.config, sections } as never, true, undefined, true)) as never
})

describe("lastfm section heights", () => {
  it("covers what Chrome, Firefox and WebKit draw, at most 2px over", () => {
    // fetchData asks Last.fm for as many items as each max; the mock is fetched once.
    const LISTS = {
      recent_tracks_max: "recentTracks",
      top_artists_max: "topArtists",
      top_albums_max: "topAlbums",
      top_tracks_max: "topTracks",
    } as const
    const fetched = (data: LastFmData, options: Record<string, unknown>): LastFmData => {
      const out = { ...data }
      for (const [option, list] of Object.entries(LISTS)) {
        const max = options[option]
        if (typeof max === "number") out[list] = take(data[list] as unknown[], max) as never
      }
      return out
    }
    expect(wrongHeights(plugin, mock, VARIANTS, MEASURED, { fetched })).toEqual([])
  })
})
