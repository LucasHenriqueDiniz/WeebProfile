/**
 * Height of every Last.fm section, in each display style, against what the browsers draw.
 *
 * Until 11/2026 a hidden title still counted 40px (and the statistics' gap after it), the
 * terminal counted its body's 8px padding once per section (32px of blank space with all
 * five) and 17px a TerminalList line for 16, the terminal statistics 52px without the
 * featured track for the 72 it draws (20px cut), and the `default` grid 252/291px whatever
 * the number of items. That grid took its height from its first item's image: the mock's
 * portrait artist photo drew 287px, a square one 252 (35px of blank space), and a 2:3
 * portrait 345 (58px cut). Its cells now have a fixed height.
 *
 * `MEASURED` is what Chrome 158, Firefox 150 and WebKit 26.4 (Playwright 1.60) drew on
 * 18/11/2026, measured by `pnpm --filter @weeb/svg-generator audit:heights -- --variants
 * --engine=all` (renderPlugins, theme CSS, no terminal header): each section alone and all
 * of them in one card, with every option that changes the height, and the mock changed as
 * `VARIANTS` says.
 */

const take = <T>(list: T[], n: number): T[] => Array.from({ length: n }, (_, i) => ({ ...list[i % list.length]! }))
const items =
  (n: number) =>
  (m: LastFmData): LastFmData => ({
    ...m,
    topArtists: take(m.topArtists, n),
    topAlbums: take(m.topAlbums, n),
    topTracks: take(m.topTracks, n),
    recentTracks: take(m.recentTracks, n),
  })

const svg = (w: number, h: number): string =>
  `data:image/svg+xml;base64,${Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}"><rect width="${w}" height="${h}" fill="#888"/></svg>`).toString("base64")}`
const firstImage =
  (image: string | null) =>
  (m: LastFmData): LastFmData => {
    const set = <T extends { image?: string | null }>(list: T[]): T[] =>
      list.map((item, i) => ({ ...item, image: i === 0 ? image : svg(300, 300) }))
    return { ...m, topArtists: set(m.topArtists), topAlbums: set(m.topAlbums), topTracks: set(m.topTracks) }
  }

